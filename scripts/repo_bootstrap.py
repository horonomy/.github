# Content
# ---------------------------------------------------------------------------
def render_adoption_block(*, org: str, repo: str, governance_version: int) -> str:
    return (
        f"{BLOCK_BEGIN}\n"
        f"Read the org baseline first: [horonomy/.github/CLAUDE.md](https://github.com/horonomy/.github/blob/main/CLAUDE.md).\n"
        f"It owns company-wide policy — see [`governance/README.md`](https://github.com/horonomy/.github/blob/main/governance/README.md)\n"
        f"for the full Company -> Product -> Repository precedence rule. This file adds\n"
        f"only what is true of *this* repository (`{org}/{repo}`) and does not repeat the\n"
        f"baseline; it may add to or strengthen a company rule, never weaken a\n"
        f"non-waivable one.\n\n"
        f"Adopted governance_version: {governance_version}. Regenerate this block with\n"
        f"`python3 scripts/repo_bootstrap.py adopt {repo} --org {org}` from a\n"
        f"`horonomy/.github` checkout — do not hand-edit between the markers.\n"
        f"{BLOCK_END}"
    )


def render_agents_md() -> str:
    return (
        f"{AGENTS_MARKER}\n"
        f"<!-- Source: horonomy/.github scripts/repo_bootstrap.py. Do not hand-edit. -->\n\n"
        f"# AGENTS.md\n\n"
        f"Compatibility pointer for tooling that reads `AGENTS.md` instead of\n"
        f"`CLAUDE.md`. This file carries no independent policy content — see\n"
        f"[`CLAUDE.md`](./CLAUDE.md) (or [`.claude/CLAUDE.md`](./.claude/CLAUDE.md)),\n"
        f"the actual entrypoint for this repository (ADR-0005 decision #5: an adapter\n"
        f"never forks a second copy of canonical content).\n"
    )


