def _cmd_check(args: argparse.Namespace) -> int:
    repo = Path(args.repo).expanduser().resolve()
    has_adoption = (repo / ADOPTION_MARKER_FILENAME).is_file()
    has_consumption = (repo / CONSUMPTION_MARKER_FILENAME).is_file()
    # Independent review (HORO-982): the original version picked exactly one
    # of check()/check_consumption() by `is_consumer`, so a repo carrying
    # BOTH markers at once (the same state doctor's cross_org_contamination
    # check flags as FAIL) silently only reported consumption drift here —
    # the adoption marker's own state went unmentioned. Report both blocks
    # whenever both markers are present, with an explicit contamination
    # line, rather than picking a side.
    results: list[tuple[str, str, str]] = []
    if has_adoption and has_consumption:
        results.append(
            (
                "distribution_mode",
                "FAIL",
                f"both {ADOPTION_MARKER_FILENAME} and {CONSUMPTION_MARKER_FILENAME} are present — "
                f"this repo is in two distribution modes at once; see scripts/doctor.py's "
                f"cross_org_contamination check for the full picture",
            )
        )
        results.extend(check(repo))
        results.extend(check_consumption(repo))
    elif has_consumption:
        results.extend(check_consumption(repo))
    else:
        results.extend(check(repo))
    worst = "PASS"
    for name, status, detail in results:
        print(f"{name}: {status} — {detail}")
        if status == "FAIL":
            worst = "FAIL"
        elif status == "WARN" and worst != "FAIL":
            worst = "WARN"
    print(f"overall: {worst}")
    return 1 if worst == "FAIL" else 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)

    p_adopt = sub.add_parser("adopt", help="Adopt or refresh governance in a target repo.")
    p_adopt.add_argument("repo", help="Path to the target repo.")
    p_adopt.add_argument("--org", default="horonomy", help="GitHub org the target repo belongs to (default: horonomy).")
    p_adopt.add_argument("--force", action="store_true", help="Adopt even if the repo has uncommitted changes.")
    p_adopt.add_argument("--dry-run", action="store_true", help="Report what would change without writing anything.")
    p_adopt.set_defaults(func=_cmd_adopt)

    p_consume = sub.add_parser(
        "consume", help="Project applicable shared skills into a non-Horonom repo (HORO-982)."
    )
    p_consume.add_argument("repo", help="Path to the target repo.")
    p_consume.add_argument(
        "--org", help="Override the org resolved from the repo's remote (rarely needed)."
    )
    p_consume.add_argument("--force", action="store_true", help="Consume even if the repo has uncommitted changes or resolves to the horonomy org.")
    p_consume.add_argument("--dry-run", action="store_true", help="Report what would change without writing anything.")
    p_consume.set_defaults(func=_cmd_consume)

    p_check = sub.add_parser("check", help="Report adoption/consumption drift; needs only the target repo.")
    p_check.add_argument("repo", help="Path to the target repo.")
    p_check.set_defaults(func=_cmd_check)

    return parser


def main(argv: list[str]) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
